import { z } from 'zod';

const locationSchema = z.object({
  latitude: z.number().nullable().optional(),
  longitude: z.number().nullable().optional(),
  readableName: z.string().max(200).optional(),
});

/**
 * Location can arrive in two forms:
 *
 * 1. JSON request:
 *    location: { latitude, longitude, readableName }
 *
 * 2. multipart/form-data:
 *    location: '{"latitude": 24.86, "longitude": 67.01, "readableName": "Karachi"}'
 */
const locationFieldSchema = z
  .union([
    locationSchema,
    z.string().transform((value, ctx) => {
      if (!value.trim()) {
        return undefined;
      }

      try {
        const parsed = JSON.parse(value);

        const result = locationSchema.safeParse(parsed);

        if (!result.success) {
          ctx.addIssue({
            code: z.ZodIssueCode.custom,
            message: 'Invalid location data',
          });

          return z.NEVER;
        }

        return result.data;
      } catch {
        ctx.addIssue({
          code: z.ZodIssueCode.custom,
          message: 'Location must be valid JSON',
        });

        return z.NEVER;
      }
    }),
  ])
  .optional();

export const createMemorySchema = z.object({
  body: z.object({
    groupId: z
      .string()
      .regex(/^[0-9a-fA-F]{24}$/, 'Invalid Group ID format'),

    /*
     * imageUrl and cloudinaryPublicId are intentionally removed.
     * They will be generated by the backend after uploading
     * the image to Cloudinary.
     */

    memoryDate: z
      .string()
      .regex(
        /^\d{4}-\d{2}-\d{2}$/,
        'Memory date must be in YYYY-MM-DD format'
      )
      .refine((value) => {
        const date = new Date(`${value}T00:00:00.000Z`);
        return (
          Number.isFinite(date.getTime()) &&
          date.toISOString().slice(0, 10) === value &&
          value <= new Date().toISOString().slice(0, 10)
        );
      }, 'Memory date must be a valid calendar date and cannot be in the future'),

    caption: z
      .string()
      .max(500, 'Caption cannot exceed 500 characters')
      .optional()
      .default(''),

    location: locationFieldSchema,
  }),
});

export const updateMemorySchema = z.object({
  params: z.object({
    id: z
      .string()
      .regex(/^[0-9a-fA-F]{24}$/, 'Invalid Memory ID format'),
  }),

  body: z.object({
    caption: z
      .string()
      .max(500, 'Caption cannot exceed 500 characters')
      .optional(),

    location: locationFieldSchema,
  }),
});
